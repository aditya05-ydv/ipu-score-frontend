// ── Helper: get subjects for a programme + semester ──────
export const getSubjects = (programmeId, semesterNum) => {
  const prog = SCHEMES[programmeId];
  if (!prog) return [];
  return prog.semesters[semesterNum] || [];
};

// ── Helper: get all available semesters for a programme ──
export const getSemesters = (programmeId) => {
  const prog = SCHEMES[programmeId];
  if (!prog) return [];
  return Object.keys(prog.semesters).map(Number);
};

